"""Generate docs/PERMISSIONS.md from platform_common/permissions_matrix.yaml (LLD-0 §3.3).

    python scripts/gen_permissions_doc.py          # rewrite the page
    python scripts/gen_permissions_doc.py --check  # exit 1 if the page is stale (CI)
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MATRIX = ROOT / "libs" / "platform_common" / "platform_common" / "permissions_matrix.yaml"
DOC = ROOT / "docs" / "PERMISSIONS.md"
LABELS = {"owner": "Owner", "admin": "Admin", "billing": "Billing", "ca": "CA"}

HEADER = """# Role permissions

<!-- Generated by scripts/gen_permissions_doc.py from
     libs/platform_common/platform_common/permissions_matrix.yaml. Don't edit by hand. -->

The Release 1 role table (BRD under ON-5). The Product Owner owns the cells; the YAML
file is the only copy in code. Every business route declares one permission with
`require(Permission.X)`, and the server refuses a role without it with the same
**404 "not found"** as an unknown business (ON-2). Only the log records the reason
(`role_denied`). Hiding a button in the UI is never the control.

"""

FOOTER = """
## Rules outside the table

- A caller who isn't an active member of the business gets 404 (`not_member`), the same
  as for a business that doesn't exist or a malformed ID.
- A support user under an owner's grant may only read (`*.view`); any other permission
  is refused (`support_no_grant`).
- An unknown role string gets no permissions.
- Until LLD-1's identity reshape, identity's own member and audit routes still check the
  six stock-era roles its tables allow (`app.modules.identity.models.Role`). No other
  module can use them.
"""


def render() -> str:
    data = yaml.safe_load(MATRIX.read_text())
    roles = data["roles"]
    lines = [HEADER.rstrip("\n") + "\n", "| Permission | Role-table row | " + " | ".join(LABELS[r] for r in roles) + " |"]
    lines.append("|---|---|" + "---|" * len(roles))
    notes = []
    for name, entry in data["permissions"].items():
        cells = ["Yes" if r in entry["roles"] else "No" for r in roles]
        lines.append(f"| `{name}` | {entry['row']} | " + " | ".join(cells) + " |")
        if entry.get("note"):
            notes.append(f"- `{name}`: {entry['note']}")
    out = "\n".join(lines) + "\n"
    if notes:
        out += "\n" + "\n".join(notes) + "\n"
    out += "\n## Actions that need a reason\n\n"
    out += "A blank or whitespace-only reason is refused (422 `reason_required`). The reason goes into the audit row.\n\n"
    out += "\n".join(f"- `{a}`" for a in data["reason_required"]) + "\n"
    return out + FOOTER


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if DOC.read_text() != text:
            print(f"{DOC.relative_to(ROOT)} is stale; run python scripts/gen_permissions_doc.py")
            return 1
        print("permissions doc is current")
        return 0
    DOC.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
