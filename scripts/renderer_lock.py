"""Regenerates the renderer's two lock files (TD-9, D-042). Run it only to upgrade
WeasyPrint or the native libraries; the build itself (scripts/build_renderer.py) reads the
locks and needs neither the solver nor a resolver.

    renderer/requirements.txt  WeasyPrint and every dependency, pinned, with the sha256 of
                               the aarch64 wheel and the x86_64 one (the x86_64 build is
                               only for the CI smoke render)
    renderer/natives.lock      the conda-forge packages that hold the shared objects
                               WeasyPrint loads, and everything they link to, per platform

Needs py-rattler (pip install py-rattler==0.28.1) and network access to PyPI and
conda.anaconda.org. Usage: python scripts/renderer_lock.py
"""

import asyncio
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from build_renderer import ARCHES, closure  # noqa: E402

WEASYPRINT = "weasyprint==70.0"
NATIVE_SPECS = ["pango ==1.58.2"]  # pulls glib, harfbuzz, fontconfig, freetype, fribidi
# AL2023, which the python3.12 Lambda runtime runs on, has glibc 2.34; only packages built
# for that or older can be chosen.
GLIBC = "2.34"


def lock_wheels() -> str:
    found: dict[str, tuple[str, set[str]]] = {}
    for arch in ARCHES.values():
        with tempfile.TemporaryDirectory() as d:
            subprocess.run(
                [sys.executable, "-m", "pip", "download", "--quiet", "--only-binary=:all:",
                 "--implementation", "cp", "--python-version", "3.12",
                 *[a for tag in arch["wheel"] for a in ("--platform", tag)], "-d", d, WEASYPRINT],
                check=True,
            )
            for f in sorted(os.listdir(d)):
                name, version = f.split("-")[:2]
                name = re.sub(r"[-_.]+", "-", name).lower()
                digest = hashlib.sha256(Path(d, f).read_bytes()).hexdigest()
                prev = found.setdefault(name, (version, set()))
                if prev[0] != version:
                    sys.exit(f"{name} resolves to {prev[0]} and {version} on different platforms")
                prev[1].add(digest)
    lines = ["# Generated by scripts/renderer_lock.py; do not edit by hand."]
    for name, (version, digests) in sorted(found.items()):
        entry = [f"{name}=={version}"] + [f"    --hash=sha256:{h}" for h in sorted(digests)]
        lines.append(" \\\n".join(entry))
    return "\n".join(lines) + "\n"


async def lock_natives() -> str:
    from rattler import GenericVirtualPackage, PackageName, Platform, Version, install, solve
    from rattler.package.build_string import BuildString

    virtual = [GenericVirtualPackage(PackageName(n), Version(v), BuildString("0"))
               for n, v in (("__glibc", GLIBC), ("__unix", "0"), ("__linux", "6.1"))]
    lines = ["# Generated by scripts/renderer_lock.py; do not edit by hand.",
             "# subdir name version build sha256 url license"]
    for arch in ARCHES.values():
        records = await solve(sources=["conda-forge"], specs=NATIVE_SPECS, virtual_packages=virtual,
                              platforms=[Platform(arch["conda"]), Platform("noarch")])
        with tempfile.TemporaryDirectory() as prefix:
            await install(records, target_prefix=prefix, show_progress=False)
            owner = {}
            for meta in Path(prefix, "conda-meta").glob("*.json"):
                m = json.loads(meta.read_text())
                for p in m["paths_data"]["paths"]:
                    owner[p["_path"]] = m
            needed = {}
            for soname in closure(Path(prefix, "lib"), arch["base"]):
                real = os.path.relpath(os.path.realpath(Path(prefix, "lib", soname)), prefix)
                m = owner[real]
                needed[m["name"]] = m
        for name, m in sorted(needed.items()):
            lines.append(" ".join([arch["conda"], name, m["version"], m["build"], m["sha256"], m["url"],
                                   m["license"].replace(" ", "_")]))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "renderer" / "requirements.txt").write_text(lock_wheels())
    (ROOT / "renderer" / "natives.lock").write_text(asyncio.run(lock_natives()))
    print("wrote renderer/requirements.txt and renderer/natives.lock")
